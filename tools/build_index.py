#!/usr/bin/env python3
"""Write INDEX.md: one line per entry. Skills read this file first.

Usage: python3 tools/build_index.py
"""
from collections import Counter
from lib import ROOT, load_all

def main():
    entries, _ = load_all()
    out = ["# Index", "", "Generated by `tools/build_index.py`. Do not edit by hand.", ""]
    c = Counter(m["status"] for m in entries.values())
    out += ["Status: " + ", ".join(f"{k} {v}" for k, v in sorted(c.items())), ""]
    def table(title, rows, head):
        out.extend([f"## {title}", "", "| " + " | ".join(head) + " |", "|" + "---|" * len(head)])
        out.extend("| " + " | ".join(r) + " |" for r in rows); out.append("")
    link = lambda m: f"[`{m['slug']}`]({m['_path'].relative_to(ROOT)})"
    by = lambda k: [m for m in entries.values() if m["kind"] == k]
    table("Narratives", [[link(m), m["summary"], f"{m['duration']['min']}–{m['duration']['max']} s", m["status"]] for m in by("narrative")], ["Slug", "Summary", "Length", "Status"])
    table("Styles", [[link(m), m["summary"], m["status"]] for m in by("style")], ["Slug", "Summary", "Status"])
    groups = {}
    for m in by("primitive"): groups.setdefault(m["group"], []).append(m)
    for g, ms in groups.items():
        table(f"Primitives: {g}", [[link(m), m["summary"], m["energy"], m["status"]] for m in ms], ["Slug", "Summary", "Energy", "Status"])
    (ROOT / "INDEX.md").write_text("\n".join(out), encoding="utf-8")
    print(f"INDEX.md written, {len(entries)} entries")

if __name__ == "__main__":
    main()
