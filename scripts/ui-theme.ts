// Writes the studio's theme, and the themes a film can put on its stage
// (`theme.ui`), from the theme token resolver.
//
// The studio chrome wears ui's *Graphite* preset: no chroma, a narrow tonal
// range, no shadows. The seed is the one in ui's docs/site-design-brief.md
// (§5.5); the resolver turns it into the full `--ui-*` token set, so the panel,
// the dock and the notes read the same tokens any ui component would.
//
//   node scripts/ui-theme.ts [path/to/ui]     (default: ../ui)
//
// The output is committed, so building motion never needs the ui checkout.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const uiRoot = resolve(process.argv[2] ?? '../ui');
const tokens = await import(pathToFileURL(resolve(uiRoot, 'packages/tokens/src/index.ts')).href);

const font = 'Aspekta, ui-sans-serif, system-ui, sans-serif';
export const GRAPHITE = {
  colors: {
    bg: '#F3F3F2', surface: '#F8F8F7', muted: '#E7E7E6',
    textPrimary: '#3B3B3A', textMuted: '#6A6A69', border: '#D9D9D8', accent: '#585857',
  },
  dark: {
    bg: '#1E1E1E', surface: '#252525', muted: '#2B2B2B',
    textPrimary: '#D4D4D3', textMuted: '#9A9A99', border: '#3A3A3A', accent: '#C4C4C3',
  },
  typography: { baseSize: 16, fontBody: font, fontDisplay: font },
  shape: { radiusPx: { sm: 4, md: 6, lg: 12, xl: 16, '2xl': 24, pill: 999 }, borderWidthPx: 1, shadow: 'none' },
};

const pair = tokens.resolveThemePair(GRAPHITE);
for (const issue of pair.issues) console.warn(`graphite: ${issue.message ?? JSON.stringify(issue)}`);
const css = tokens.toCss(pair, { scope: '[data-ui-theme="graphite"]', scheme: 'auto', includeBase: true });

const out = resolve(import.meta.dirname, '../src/studio/theme/graphite.css.ts');
writeFileSync(out, [
  '// Generated by scripts/ui-theme.ts from the theme token resolver. Do not edit.',
  `export const GRAPHITE_CSS = ${JSON.stringify(css)};`,
  '',
].join('\n'));
console.log(`wrote ${out} (${css.length} bytes)`);

// Stage themes: what `theme.ui` puts on a film's stage, so placeholders and demo
// content wear the ui library's fonts, colours and radii in stills and renders,
// not only in the studio. Zero is Diorama's own theme, with its authored map;
// Graphite and Hockney are the approved presets of the ui site (theme-presets.ts).
const STAGE_SEEDS: Record<string, [unknown, unknown?]> = {
  zero: [tokens.THEME_ZERO, tokens.resolveZeroPairOptions],
  graphite: [GRAPHITE],
  hockney: [{
    colors: { bg: '#FFFFFF', surface: '#FAEBE6', muted: '#F5DED7', textPrimary: '#1D1D1F', textMuted: '#6E6E73', border: '#E6E3E1', accent: '#1672C4' },
    dark: { bg: '#0E1620', surface: '#15202C', muted: '#1C2836', textPrimary: '#F2F1EE', textMuted: '#A3A9B1', border: '#2A3644', accent: '#5CB8F0' },
    typography: { baseSize: 16, fontBody: font, fontDisplay: font },
    shape: { controlShape: 'full', radiusPx: { sm: 6, md: 12, lg: 20, xl: 28, '2xl': 36 }, shadow: 'subtle' },
  }],
};
const stage: Record<string, string> = {};
for (const [name, [seed, options]] of Object.entries(STAGE_SEEDS)) {
  const p = tokens.resolveThemePair(seed, options);
  for (const issue of p.issues) console.warn(`${name}: ${issue.message ?? JSON.stringify(issue)}`);
  stage[name] = tokens.toCss(p, { scope: `.m-stage[data-ui-theme="${name}"]`, scheme: 'auto', includeBase: true });
}
const stageOut = resolve(import.meta.dirname, '../src/dom/ui-themes.css.ts');
writeFileSync(stageOut, [
  '// Generated by scripts/ui-theme.ts from the theme token resolver. Do not edit.',
  '// The bundled themes a film can wear on its stage with `theme.ui`.',
  `export const UI_THEMES = ${JSON.stringify(stage, null, 2)} as const;`,
  'export type UiThemeName = keyof typeof UI_THEMES;',
  '/** Aspekta (SIL OFL 1.1, see src/studio/theme/fonts/OFL.txt), embedded so the stage needs no font file. */',
  `export const ASPEKTA_URL = ${JSON.stringify(`data:font/woff2;base64,${readFileSync(resolve(import.meta.dirname, '../src/studio/theme/fonts/AspektaVF.woff2')).toString('base64')}`)};`,
  '',
].join('\n'));
console.log(`wrote ${stageOut} (${Object.values(stage).reduce((a, c) => a + c.length, 0)} bytes)`);
